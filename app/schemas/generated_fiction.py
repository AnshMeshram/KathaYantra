"""AI-Generated Creative Fiction Schema for KathaYantra.

Maintains strict, irrevocable segregation between authentic cultural folklore records
and synthetic creative stories generated by local AI (Ollama / Gemma 2).
"""

from datetime import datetime, timezone
from enum import Enum
import re
from typing import Literal
from pydantic import BaseModel, Field, field_validator
from app.schemas.story import VerificationStatusEnum


class GeneratedFictionRecord(BaseModel):
    """Schema for AI-generated creative fiction narratives inspired by world folklore."""

    id: str = Field(
        ...,
        min_length=6,
        description="Unique fictional record identifier (format: AI-FIC-[INDEX], e.g. AI-FIC-001)",
    )
    title: str = Field(..., min_length=2, max_length=300, description="Title of the creative narrative")
    content_type: Literal["ai_generated_fiction"] = Field(
        default="ai_generated_fiction",
        description="Fixed type token identifying synthetic fiction",
    )
    story_text: str = Field(..., min_length=20, max_length=150000, description="Complete generated fictional story text")
    inspiration_story_ids: list[str] = Field(
        default_factory=list,
        description="IDs of authentic KathaYantra stories used as creative inspiration",
    )
    inspiration_source_ids: list[str] = Field(
        default_factory=list,
        description="IDs of external folklore references or motifs consulted",
    )
    model_provider: str = Field(default="ollama", description="Local inference runtime provider (e.g. ollama)")
    model_tag: str = Field(default="gemma2", description="Exact model weight identifier (e.g. gemma2, gemma2:9b)")
    prompt_template_version: str = Field(default="1.0.0", description="Semantic version of generation prompt template")
    generated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of creative generation",
    )
    fiction_disclaimer: str = Field(
        default=(
            "This narrative is an AI-generated work of creative fiction inspired by traditional folklore motifs. "
            "It is not an authentic traditional folklore record and must not be cited as historical folklore."
        ),
        min_length=20,
        description="Mandatory prominent disclaimer separating synthetic content from real folklore",
    )
    verification_status: VerificationStatusEnum = Field(
        default=VerificationStatusEnum.NEEDS_REVIEW,
        description="Quality and safety review stage of the generated text",
    )
    record_version: str = Field(default="1.0.0", description="Semantic record version")
    schema_version: str = Field(default="2.0.0", description="Generated fiction schema contract version")

    @field_validator("id")
    @classmethod
    def validate_fiction_id(cls, v: str) -> str:
        v = v.strip()
        if not re.match(r"^AI-FIC-[0-9]{3,}$", v):
            raise ValueError(
                f"Invalid fiction record ID '{v}'. Expected format: AI-FIC-[INDEX] (e.g. AI-FIC-001)"
            )
        return v

    @field_validator("fiction_disclaimer")
    @classmethod
    def validate_disclaimer(cls, v: str) -> str:
        if not v or len(v.strip()) < 20:
            raise ValueError("A clear, non-empty fiction_disclaimer of at least 20 characters is mandatory.")
        return v.strip()

