"""Tests for AI-Generated Fiction Schema and Segregation Enforcement (Phase 2)."""

from pydantic import ValidationError
import pytest
from app.schemas.generated_fiction import GeneratedFictionRecord
from app.schemas.source import RightsStatusEnum, StorySource
from app.schemas.story import (
    CategoryEnum,
    ContentOriginEnum,
    StoryRecord,
    VerificationStatusEnum,
)


def test_valid_generated_fiction_record():
    """Verify that a valid AI-generated fiction record validates cleanly."""
    fiction = GeneratedFictionRecord(
        id="AI-FIC-001",
        title="The Whispering Shadows of Kyoto",
        story_text="A traveler walking through Gion at twilight encountered an unfamiliar tea house...",
        inspiration_story_ids=["JP-FOLK-001", "JP-FOLK-004"],
        inspiration_source_ids=["nichibunken_yokai_db"],
        model_provider="ollama",
        model_tag="gemma2:9b",
        prompt_template_version="1.2.0",
        fiction_disclaimer=(
            "This narrative is an AI-generated work of creative fiction inspired by traditional Japanese yōkai motifs. "
            "It is not an authentic traditional folklore record."
        ),
    )

    assert fiction.id == "AI-FIC-001"
    assert fiction.content_type == "ai_generated_fiction"
    assert fiction.model_tag == "gemma2:9b"
    assert len(fiction.inspiration_story_ids) == 2


def test_fiction_id_format_enforcement():
    """Verify that fiction ID must match the AI-FIC-[INDEX] pattern."""
    with pytest.raises(ValidationError):
        GeneratedFictionRecord(
            id="JP-FOLK-999",  # Attempting to use a real folklore ID
            title="Fake Story",
            story_text="Some long fictional prose for validation testing...",
        )


def test_fiction_missing_disclaimer_rejected():
    """Verify that omitting or passing an inadequate fiction disclaimer fails validation."""
    with pytest.raises(ValidationError) as exc:
        GeneratedFictionRecord(
            id="AI-FIC-002",
            title="Story Without Disclaimer",
            story_text="A traveler entered a forest with mysterious spirits...",
            fiction_disclaimer="",  # Empty disclaimer
        )
    assert "fiction_disclaimer" in str(exc.value)

    with pytest.raises(ValidationError) as exc:
        GeneratedFictionRecord(
            id="AI-FIC-003",
            title="Short Disclaimer",
            story_text="A traveler entered a forest with mysterious spirits...",
            fiction_disclaimer="AI generated",  # Too short (< 20 chars)
        )
    assert "at least 20 characters" in str(exc.value)


def test_attempt_to_publish_fiction_as_folklore_fails():
    """Verify that an AI fiction record cannot be validated as a published StoryRecord."""
    fiction_payload = {
        "id": "AI-FIC-001",
        "title": "Synthetic Myth",
        "story_text": "A synthetic narrative generated by an LLM...",
        "content_type": "ai_generated_fiction",
    }

    # Cannot instantiate StoryRecord with fiction ID
    with pytest.raises(ValidationError):
        StoryRecord(
            id=fiction_payload["id"],
            title=fiction_payload["title"],
            country_code="JP",
            category=CategoryEnum.FOLKLORE,
            summary="A synthetic tale.",
            sources=[StorySource(title="AI", url="https://example.com/ai")],
            content_origin=ContentOriginEnum.AI_GENERATED_FICTION,
        )
